"""What an exported file contains, built from one saved answer or extraction.

The Word and PowerPoint exports show exactly the same information, so it is
gathered here once, as plain text ready to print: the request, the answer or
the extracted fields, the Critic's verdict written in sentences, and the
sources with the text of each passage. The two renderers only lay it out.

Nothing here calls the LLM or the database: the input is a message already
read back and validated by the API schema (MessageOut).
"""

import re
from dataclasses import dataclass, field
from datetime import datetime
from typing import Literal

from app.api.schemas import CitationOut, IssueOut, MessageOut, ReviewOut

ExportKind = Literal["answer", "extraction"]
ExportFormat = Literal["docx", "pptx"]


@dataclass(frozen=True)
class ExportTexts:
    """Every fixed text of an exported file, in one place.

    The interface writes its own texts (frontend/src/lib/i18n.ts); a file must
    be readable without it, so the backend has its own copy. Step 10 bis adds
    a French instance next to ENGLISH.
    """

    app_name: str = "ATLAS"
    answer_title: str = "Answer from your documents"
    extraction_title: str = "Key fields of {filename} ({document_type})"
    document_types: dict[str, str] = field(
        default_factory=lambda: {"invoice": "invoice", "contract": "contract", "other": "document"}
    )
    session_label: str = "Session"
    question_heading: str = "Question"
    request_heading: str = "Request"
    answer_heading: str = "Answer"
    fields_heading: str = "Extracted fields"
    field_column: str = "Field"
    value_column: str = "Value"
    page_column: str = "Page"
    not_found: str = "Not found"
    page_short: str = "p. {page}"
    no_page: str = "–"
    review_heading: str = "Critic's verdict"
    review_ok: str = "Checked by the Critic: no problem found."
    review_ok_rules_only: str = "Checked by the Critic (rules only): no problem found."
    review_one_issue: str = "The Critic found 1 problem."
    review_many_issues: str = "The Critic found {count} problems."
    review_certain: str = "Certain"
    review_to_check: str = "To check"
    review_to_check_note: str = "Flagged by the model, which can be wrong: compare with the source."
    review_in_table: str = "Problems about a field are shown next to its value."
    issue_texts: dict[str, str] = field(
        default_factory=lambda: {
            "invented_citations": "Citations invented by the model were removed.",
            "no_citation": "The answer cites no source.",
            "uncited_sentence": "A sentence cites no source.",
            "unsupported_number": "A number appears in none of the cited passages.",
            "unsupported_claim": "No passage seems to state this sentence.",
            "missing_required_field": "Required field not found.",
            "value_not_found": "This value does not appear in the pages read.",
            "wrong_page": "This value is not on the page given.",
            "unreadable_date": "This is not a readable date.",
            "unreadable_amount": "This is not a readable amount.",
        }
    )
    sources_heading: str = "Sources"
    source_used_for: str = "Used for: {labels}"
    footer: str = "Generated by ATLAS on {date} from the saved session."
    date_format: str = "{day} {month} {year}, {time} UTC"
    months: tuple[str, ...] = (
        "January",
        "February",
        "March",
        "April",
        "May",
        "June",
        "July",
        "August",
        "September",
        "October",
        "November",
        "December",
    )

    def format_date(self, moment: datetime) -> str:
        """23 October 2026, 19:20 UTC (month names come from the texts, not the system)."""
        return self.date_format.format(
            day=moment.day,
            month=self.months[moment.month - 1],
            year=moment.year,
            time=f"{moment:%H:%M}",
        )


ENGLISH = ExportTexts()


class NotExportableError(Exception):
    """The message is not a result that can be exported (a question or a refusal)."""


@dataclass(frozen=True)
class ExportSource:
    """One passage behind the result: shown with its file, page and text."""

    display: str  # as in the answer, e.g. "[contract.pdf, p. 4]"
    filename: str
    page: int
    text: str  # made readable (line breaks of the page layout joined)
    used_for: list[str]  # extraction: labels of the fields taken from it


@dataclass(frozen=True)
class ExportRow:
    """One extracted field, as printed in the table."""

    label: str
    value: str  # the not_found text when the field was not found
    page: str  # "p. 1", or the no_page text
    issues: list[str]  # problems the Critic found for this field


@dataclass(frozen=True)
class ExportReview:
    """The Critic's verdict, written in sentences."""

    summary: str
    certain: list[str]  # found by the code
    to_check: list[str]  # found by the model
    note: str | None  # extraction: problems are next to the fields


@dataclass(frozen=True)
class ExportContent:
    kind: ExportKind
    title: str
    session_title: str | None
    request: str  # the question, or the extraction request
    answer: str | None  # answer text with its citations; None for an extraction
    rows: list[ExportRow]  # extracted fields; empty for an answer
    review: ExportReview | None
    sources: list[ExportSource]
    generated_at: datetime
    texts: ExportTexts


def readable_text(text: str) -> str:
    """Join the line breaks of the page layout, as the interface does (lib/text.ts).

    Only breaks after . ! ? or : and empty lines are kept. Used for display
    only: the stored passages are never changed.
    """
    text = re.sub(r"\r\n?", "\n", text)
    text = re.sub(r"[ \t]+\n", "\n", text)
    text = re.sub(r"([^.!?:\n])\n(?!\n)", r"\1 ", text)
    text = re.sub(r" {2,}", " ", text)
    return text.strip()


def build_export(
    message: MessageOut,
    question: MessageOut | None,
    session_title: str | None,
    generated_at: datetime,
    texts: ExportTexts = ENGLISH,
) -> ExportContent:
    """The content of the file exported for one saved assistant message.

    Raises NotExportableError for a question, a refusal, or an extraction
    without its fields.
    """
    if message.role != "assistant" or message.status != "answered":
        raise NotExportableError("only an answered message can be exported")
    request = question.content if question is not None else ""

    if message.mode == "extract":
        extraction = message.extraction
        if extraction is None:
            raise NotExportableError("the extraction has no saved fields")
        issues = message.review.issues if message.review is not None else []
        document_type = texts.document_types.get(extraction.document_type, extraction.document_type)
        return ExportContent(
            kind="extraction",
            title=texts.extraction_title.format(
                filename=extraction.filename, document_type=document_type
            ),
            session_title=session_title,
            request=request,
            answer=None,
            rows=[
                ExportRow(
                    label=item.label,
                    value=item.value if item.value is not None else texts.not_found,
                    page=(
                        texts.page_short.format(page=item.page)
                        if item.page is not None
                        else texts.no_page
                    ),
                    issues=[
                        issue_text(issue, texts) for issue in issues if issue.field == item.name
                    ],
                )
                for item in extraction.fields
            ],
            review=build_review(message.review, texts, extraction=True),
            sources=extraction_sources(
                [(item.label, item.source) for item in extraction.fields], texts
            ),
            generated_at=generated_at,
            texts=texts,
        )

    return ExportContent(
        kind="answer",
        title=texts.answer_title,
        session_title=session_title,
        request=request,
        answer=message.content,
        rows=[],
        review=build_review(message.review, texts, extraction=False),
        sources=answer_sources(message.citations),
        generated_at=generated_at,
        texts=texts,
    )


def issue_text(issue: IssueOut, texts: ExportTexts) -> str:
    """The problem in words, followed by the sentence concerned when there is one."""
    text = texts.issue_texts.get(issue.code, issue.code)
    if issue.sentence:
        return f"{text} “{issue.sentence}”"
    return text


def build_review(
    review: ReviewOut | None, texts: ExportTexts, *, extraction: bool
) -> ExportReview | None:
    if review is None:
        return None
    if not review.issues:
        summary = texts.review_ok if review.model_checked else texts.review_ok_rules_only
        return ExportReview(summary=summary, certain=[], to_check=[], note=None)

    count = len(review.issues)
    summary = texts.review_one_issue if count == 1 else texts.review_many_issues.format(count=count)
    # In an extraction, a problem about a field is printed next to that field.
    listed = [issue for issue in review.issues if not (extraction and issue.field)]
    has_field_issues = len(listed) < count
    return ExportReview(
        summary=summary,
        certain=[issue_text(issue, texts) for issue in listed if issue.origin == "code"],
        to_check=[issue_text(issue, texts) for issue in listed if issue.origin == "model"],
        note=texts.review_in_table if has_field_issues else None,
    )


def answer_sources(citations: list[CitationOut]) -> list[ExportSource]:
    """One source per marker of the answer: passages of the same page are joined."""
    by_display: dict[str, list[CitationOut]] = {}
    for citation in citations:
        by_display.setdefault(citation.display, []).append(citation)
    return [
        ExportSource(
            display=display,
            filename=group[0].filename,
            page=group[0].page_number,
            text="\n\n".join(readable_text(citation.text) for citation in group),
            used_for=[],
        )
        for display, group in by_display.items()
    ]


def extraction_sources(
    fields: list[tuple[str, CitationOut | None]], texts: ExportTexts
) -> list[ExportSource]:
    """One source per passage: fields read from the same passage share it."""
    by_chunk: dict[str, tuple[CitationOut, list[str]]] = {}
    for label, source in fields:
        if source is None:
            continue
        by_chunk.setdefault(source.chunk_id, (source, []))[1].append(label)
    return [
        ExportSource(
            display=f"[{source.filename}, {texts.page_short.format(page=source.page_number)}]",
            filename=source.filename,
            page=source.page_number,
            text=readable_text(source.text),
            used_for=labels,
        )
        for source, labels in by_chunk.values()
    ]


def download_name(kind: ExportKind, generated_at: datetime, file_format: ExportFormat) -> str:
    """ATLAS_answer_2026-10-23.docx"""
    return f"ATLAS_{kind}_{generated_at:%Y-%m-%d}.{file_format}"